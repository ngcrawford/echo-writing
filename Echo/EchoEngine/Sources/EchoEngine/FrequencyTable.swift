import Foundation

/// English word frequencies as Zipf scores (log10 of frequency per billion words: *the* ≈ 7.7, *cerulean* ≈ 2.3).
/// Words missing from the table score 0.
public struct FrequencyTable: Sendable {
    private let scores: [String: Double]

    public init(scores: [String: Double]) {
        self.scores = scores
    }

    /// Reads `word<TAB>zipf×100` lines; lines starting with `#` are comments.
    public init(contentsOf url: URL) throws {
        let text = try String(contentsOf: url, encoding: .utf8)
        var scores: [String: Double] = [:]
        scores.reserveCapacity(170_000)
        for line in text.split(separator: "\n") where !line.hasPrefix("#") {
            guard let tab = line.firstIndex(of: "\t"), let value = Int(line[line.index(after: tab)...]) else { continue }
            scores[String(line[..<tab])] = Double(value) / 100
        }
        self.scores = scores
    }

    #if SWIFT_PACKAGE
    /// The table shipped with the engine (generated by `tools/gen_zipf.py`).
    public static func bundled() throws -> FrequencyTable {
        guard let url = Bundle.module.url(forResource: "zipf-en", withExtension: "tsv") else {
            throw CocoaError(.fileNoSuchFile)
        }
        return try FrequencyTable(contentsOf: url)
    }
    #endif

    public func zipf(_ word: String) -> Double {
        scores[word] ?? 0
    }

    public func contains(_ word: String) -> Bool {
        scores[word] != nil
    }
}
